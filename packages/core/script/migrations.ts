// Regenerates src/database/migrations.gen.ts from the drizzle-kit output so the Worker bundle carries the SQL.
// Run after `KIND=<kind> bunx drizzle-kit generate`: `bun run script/migrations.ts`.
import { Glob } from "bun"
import path from "node:path"

const root = path.join(import.meta.dir, "..")
const kinds = ["organization", "workspace", "session"] as const
const out = Object.fromEntries(
  await Promise.all(
    kinds.map(async (kind) => {
      const files = [...new Glob(`migrations/${kind}/*/migration.sql`).scanSync(root)].sort()
      const list = await Promise.all(
        files.map(async (f) => ({
          id: path.basename(path.dirname(f)),
          statements: (await Bun.file(path.join(root, f)).text())
            .split("--> statement-breakpoint")
            .map((s) => s.trim())
            .filter(Boolean),
        })),
      )
      return [kind, list]
    }),
  ),
)
await Bun.write(
  path.join(root, "src/database/migrations.gen.ts"),
  `// Generated by script/migrations.ts. Do not edit.\nexport const migrations = ${JSON.stringify(out, null, 2)} as const\n`,
)
